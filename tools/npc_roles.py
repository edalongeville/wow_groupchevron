"""Merges the friendly NPC roles learned in game into GroupChevron/NpcRoles.lua (shipped with the addon).

Each SavedVariables file given (WTF/Account/<account>/SavedVariables/GroupChevron.lua, copied while
the game is closed) holds GroupChevronDB.npcroles: creature ID -> role key. Their roles are merged
with the ones already in NpcRoles.lua; when two disagree, the better role wins, in the order of
Core.ROLES (read from GroupChevron/Core.lua, so both stay in step). Unknown roles are skipped.

Usage, from the repository root:
    python3 tools/npc_roles.py <GroupChevron.lua> [<GroupChevron.lua> ...]
    python3 tools/npc_roles.py --check     (fails when NpcRoles.lua is not in the generated form)
Python 3, no dependencies.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CORE = os.path.join(ROOT, "GroupChevron", "Core.lua")
OUT = os.path.join(ROOT, "GroupChevron", "NpcRoles.lua")

HEADER = """-- GroupChevron: the friendly NPC roles shipped with the addon (creature ID -> role key of
-- Core.ROLES), so an NPC gets its icon before you ever open its window. Roles learned in game
-- (GroupChevronDB.npcroles) are merged with these (the better role wins, Core.BetterRole).
--
-- Generated by tools/npc_roles.py from SavedVariables files (WTF/Account/<account>/SavedVariables/
-- GroupChevron.lua): do not edit by hand, run the tool again.

local _, ns = ...

if type(ns) == "table" then
  ns.NpcRoles = {
"""
FOOTER = """  }
end
"""

ENTRY = re.compile(r'\[\s*(\d+)\s*\]\s*=\s*"([a-z]+)"')


def role_order():
    """The role keys of Core.ROLES, best first."""
    text = open(CORE, encoding="utf-8").read()
    start = text.index("Core.ROLES = {")
    end = text.index("\n}", start)
    keys = re.findall(r'key\s*=\s*"([a-z]+)"', text[start:end])
    if not keys:
        sys.exit("no roles found in Core.ROLES (GroupChevron/Core.lua)")
    return keys


def block(text, opener):
    """The text between opener's "{" and its matching "}" (no nested tables expected), or None."""
    i = text.find(opener)
    if i < 0:
        return None
    i = text.index("{", i + len(opener) - 1)
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                return text[i + 1:j]
    sys.exit("unbalanced braces after " + opener)


def read_roles(path, opener):
    text = open(path, encoding="utf-8", errors="replace").read()
    body = block(text, opener)
    if body is None:
        return {}
    return {int(i): r for i, r in ENTRY.findall(body)}


def render(roles):
    lines = ['    [%d] = "%s",\n' % (i, roles[i]) for i in sorted(roles)]
    return HEADER + "".join(lines) + FOOTER


def main(args):
    order = role_order()
    rank = {k: n for n, k in enumerate(order)}
    shipped = read_roles(OUT, "ns.NpcRoles = {") if os.path.exists(OUT) else {}
    if args == ["--check"]:
        if open(OUT, encoding="utf-8").read() != render(shipped):
            sys.exit("GroupChevron/NpcRoles.lua is not in the generated form: run tools/npc_roles.py")
        bad = sorted(i for i, r in shipped.items() if r not in rank)
        if bad:
            sys.exit("unknown roles in NpcRoles.lua for creature IDs %s" % bad)
        print("NpcRoles.lua: %d role(s), generated form" % len(shipped))
        return
    if not args or any(a.startswith("-") for a in args):
        sys.exit(__doc__)
    merged = dict(shipped)
    added = upgraded = skipped = 0
    for path in args:
        learned = read_roles(path, '["npcroles"] = {')
        if not learned:
            print("%s: no npcroles found" % path)
        for npc, role in learned.items():
            if role not in rank:
                skipped += 1
                continue
            old = merged.get(npc)
            if old is None or old not in rank:
                merged[npc] = role
                added += 1
            elif rank[role] < rank[old]:
                merged[npc] = role
                upgraded += 1
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(render(merged))
    print("NpcRoles.lua: %d role(s) (%d added, %d upgraded, %d unknown skipped)"
          % (len(merged), added, upgraded, skipped))


if __name__ == "__main__":
    main(sys.argv[1:])
